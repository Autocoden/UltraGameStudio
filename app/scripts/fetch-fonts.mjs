/**
 * Fetch Inter + JetBrains Mono as self-hosted variable woff2 subsets.
 *
 * Why: `index.html` used to pull both families from fonts.googleapis.com at
 * runtime. UGS is a local-first desktop app (offline, intranet and CN networks
 * are all normal), so a CDN font request meant the app silently fell back to
 * `system-ui` / `ui-monospace` and rendered differently from the design.
 *
 * Both families are variable (one woff2 per unicode subset covers every
 * weight), so this stays small: 7 Inter subsets + 6 JetBrains Mono subsets.
 *
 * Usage:  node scripts/fetch-fonts.mjs
 * Output: src/assets/fonts/*.woff2  +  src/styles/fonts.css
 *
 * Licenses (SIL OFL 1.1) are fetched into public/fonts/ so they ship with the
 * built app, as the OFL requires.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Google only serves woff2 (and the variable axis) to modern browsers.
const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const FAMILIES = [
  {
    slug: 'inter',
    query: 'Inter:wght@100..900',
    cssFamily: 'Inter',
    license: {
      name: 'LICENSE-Inter.txt',
      url: 'https://raw.githubusercontent.com/rsms/inter/master/LICENSE.txt',
    },
  },
  {
    slug: 'jetbrains-mono',
    query: 'JetBrains+Mono:wght@100..800',
    cssFamily: 'JetBrains Mono',
    license: {
      name: 'LICENSE-JetBrainsMono.txt',
      url: 'https://raw.githubusercontent.com/JetBrains/JetBrainsMono/master/OFL.txt',
    },
  },
];

const woffDir = new URL('../src/assets/fonts/', import.meta.url);
const cssPath = new URL('../src/styles/fonts.css', import.meta.url);
const licenseDir = new URL('../public/fonts/', import.meta.url);

const FONT_FACE_RE = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;

function field(body, name) {
  const match = body.match(new RegExp(`${name}\\s*:\\s*([^;]+);`));
  return match ? match[1].trim() : '';
}

async function fetchOk(url) {
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
  return response;
}

async function main() {
  await mkdir(woffDir, { recursive: true });
  await mkdir(licenseDir, { recursive: true });

  const cssBlocks = [
    '/* Generated by scripts/fetch-fonts.mjs — do not edit by hand.',
    ' * Self-hosted so the app renders identically offline and on blocked networks.',
    ' */',
    '',
  ];

  for (const family of FAMILIES) {
    const cssUrl = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
    const css = await (await fetchOk(cssUrl)).text();

    let count = 0;
    for (const [, subset, body] of css.matchAll(FONT_FACE_RE)) {
      const source = field(body, 'src').match(/url\((https:[^)]+)\)/);
      if (!source) continue;

      const file = `${family.slug}-${subset}.woff2`;
      const bytes = Buffer.from(await (await fetchOk(source[1])).arrayBuffer());
      // wOF2 magic guard: never write a truncated/HTML error page as a font.
      if (bytes.length < 1024 || bytes.subarray(0, 4).toString('latin1') !== 'wOF2') {
        throw new Error(`not a woff2 payload: ${source[1]} (${bytes.length} bytes)`);
      }
      await writeFile(new URL(file, woffDir), bytes);
      count += 1;

      cssBlocks.push(
        '@font-face {',
        `  font-family: '${family.cssFamily}';`,
        '  font-style: normal;',
        `  font-weight: ${field(body, 'font-weight') || '400'};`,
        '  font-display: swap;',
        `  src: url('../assets/fonts/${file}') format('woff2');`,
        `  unicode-range: ${field(body, 'unicode-range')};`,
        '}',
        '',
      );
    }
    if (!count) throw new Error(`no @font-face blocks parsed for ${family.cssFamily}`);

    const license = await (await fetchOk(family.license.url)).text();
    await writeFile(new URL(family.license.name, licenseDir), license, 'utf8');
    console.log(`${family.cssFamily}: ${count} subsets + license`);
  }

  await writeFile(cssPath, cssBlocks.join('\n'), 'utf8');
  console.log('wrote src/styles/fonts.css');
}

await main();
